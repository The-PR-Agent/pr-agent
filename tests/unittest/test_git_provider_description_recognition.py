class TestGenericHeadersRequireStartswith:
    def test_generic_header_at_start_detected(self):
        desc = "### **Description**\nThis is the description."
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True

    def test_generic_header_with_leading_content_not_detected(self):
        """A human description quoting a generic header should not be
        misclassified as pr-agent output."""
        desc = "Here is my summary.\n### **Description**\nSome content."
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False

    def test_generic_labels_at_start(self):
        desc = "### **Labels**\nbug, enhancement"
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True

    def test_generic_labels_with_leading_not_detected(self):
        desc = "PR for review.\n### **Labels**\nbug"
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False

    def test_generic_type_at_start(self):
        desc = "### **Type**\nfeat"
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True

    def test_generic_type_with_leading_not_detected(self):
        desc = "Summary.\n### **Type**\nfeat"
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False


