"""Tests for description recognition in _is_generated_by_pr_agent.

The ratchet case from #2633: a description with leading content before
pr-agent headers should still be recognized as pr-agent output, so that
get_user_description can extract the original user text without growing
the description without bound.
"""
import types

import pytest

from pr_agent.git_providers.git_provider import GitProvider


def _make_provider(desc: str):
    """Create a bare object that has the methods we need to test,
    without instantiating the abstract class."""
    obj = types.SimpleNamespace()
    obj._description = desc
    obj.user_description = None
    obj._UNIQUE_PR_AGENT_HEADERS = GitProvider._UNIQUE_PR_AGENT_HEADERS
    # Bind the real methods from the class
    obj._is_generated_by_pr_agent = lambda d: GitProvider._is_generated_by_pr_agent(obj, d)
    obj._possible_headers = lambda: GitProvider._possible_headers(obj)
    obj._iter_description_headers = lambda d: GitProvider._iter_description_headers(obj, d)
    obj.get_user_description = lambda: GitProvider.get_user_description(obj)
    obj.get_pr_description = lambda **kw: GitProvider.get_pr_description(obj, **kw)
    obj.get_pr_description_full = lambda: desc
    return obj


# ---------------------------------------------------------------------------
# Hidden marker detection
# ---------------------------------------------------------------------------

class TestHiddenMarkerDetection:
    def test_marker_anywhere_detects(self):
        desc = ("<!-- pr-agent-generated -->\n"
                "Some text before headers.\n"
                "### **PR Type**\nbug fix")
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True

    def test_marker_in_body_not_at_start(self):
        desc = ("A sentence.\n\n<!-- pr-agent-generated -->\n\n### **PR Type**\nfeat")
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True

    def test_no_marker_no_header_returns_false(self):
        desc = "This is a plain human description."
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False


