class TestQuotedHeadersAreNotOurs:
    """A human description that quotes our headers must not be read as generated,
    otherwise get_user_description() returns '' and their text is lost."""

    def test_block_quoted_header_is_not_generated(self):
        desc = ("For reference the bot emits:\n\n"
                "> ### **PR Type**\n> Bug fix\n\nLeave my text alone.")
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False

    def test_inline_backticked_header_is_not_generated(self):
        desc = "Our template starts with `### **PR Type**` which I am not using here."
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False

    def test_indented_header_is_not_generated(self):
        desc = "Example:\n\n    ### **PR Type**\n    Bug fix\n\nNot mine."
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is False

    def test_leading_content_before_header_is_still_generated(self):
        desc = "Fixes #42\n### **PR Type**\nBug fix"
        assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True


@pytest.mark.parametrize("fence,newline", [("```", "\n"), ("~~~", "\r\n"), ("   ````python", "\n")])
def test_human_fenced_headers_roundtrip(fence, newline):
    delimiter = "~~~~" if "~" in fence else "`````"
    desc = newline.join(["İnput example:", fence, "### **pR tYpE**", "Bug fix", delimiter, "Fixes #42"])
    provider = _make_provider(desc)
    assert provider._is_generated_by_pr_agent(desc.lower()) is False
    assert provider.get_user_description() == desc


@pytest.mark.parametrize("separator", ["\r", "\v", "\f", "\x85", "\u2028", "\u2029"])
def test_non_lf_separators_do_not_create_header_boundaries(separator):
    desc = "Human text" + separator + "### **PR Type**\nFixes #42"
    provider = _make_provider(desc)
    assert provider._is_generated_by_pr_agent(desc.lower()) is False
    assert provider.get_user_description() == desc


@pytest.mark.parametrize("separator", ["\n", "\r\n"])
def test_lf_header_boundaries_remain_generated(separator):
    desc = "Leading content" + separator + "### **PR Type**\nBug fix"
    assert _make_provider(desc)._is_generated_by_pr_agent(desc.lower()) is True


@pytest.mark.parametrize("opener,closer,generated", [
    ("````", "```", False),
    ("```", "~~~", False),
    ("~~~", "```", False),
    ("~~~", "~~~~ trailing", False),
    ("```", "    ```", False),
    ("```", "", False),
    ("~~~ lang`info", "", False),
    ("````", "`````", True),
    ("~~~", "   ~~~~ \t", True),
])
def test_fence_close_controls_later_headers(opener, closer, generated):
    desc = f"Example:\n{opener}\nquoted text\n{closer}\n### **PR Type**\nBug fix"
    provider = _make_provider(desc)
    assert provider._is_generated_by_pr_agent(desc.lower()) is generated
    if not generated:
        assert provider.get_user_description() == desc


@pytest.mark.parametrize("quoted", [
    "```markdown\n### **PR Type**\nBug fix\n```",
    "~~~\n### **PR Type**\nBug fix\n~~~",
    "Our template contains `### **PR Type**`.",
    "> ### **PR Type**\n> Bug fix",
    "    ### **PR Type**\n    Bug fix",
])
@pytest.mark.parametrize("newline", ["\n", "\r\n"])
def test_generated_wrapper_preserves_quoted_headers_and_tail(quoted, newline):
    human = ("İnput example:\n" + quoted + "\nKeep This Case. Fixes #42").replace("\n", newline)
    desc = newline.join(["<!-- pr-agent-generated -->", "### **User Description**", human,
                         "___", "### **PR Type**", "Bug fix"])
    provider = _make_provider(desc)
    assert provider.get_user_description() == human
    assert provider.user_description == human


@pytest.mark.parametrize("prefix", [
    "```\n### **User Description**\nquoted\n```\n",
    "> ### **User Description**\nquoted\n",
    "    ### **User Description**\nquoted\n",
    "`### **User Description**`\nquoted\n",
    "### **PR Type**\nBug fix\n",
])
def test_selects_structural_user_header_and_later_end(prefix):
    desc = ("<!-- pr-agent-generated -->\n" + prefix +
            "### **uSeR dEsCrIpTiOn**\nİnput Fixes #42\n___\n### **PR Labels**\nbug")
    assert _make_provider(desc).get_user_description() == "İnput Fixes #42"


def test_repeated_user_header_does_not_end_extraction():
    human = "First\n### **User Description**\nSecond Fixes #42"
    desc = "### **User Description**\n" + human + "\n### **PR Description**\nGenerated"
    assert _make_provider(desc).get_user_description() == human


@pytest.mark.parametrize("suffix", ["", "\n___\nlegacy generated section"])
def test_no_next_header_fallback_starts_after_selected_header(suffix):
    desc = ("<!-- pr-agent-generated -->\n### **PR Type**\nBug fix\n"
            "### **User Description**\nHuman Fixes #42" + suffix)
    assert _make_provider(desc).get_user_description() == "Human Fixes #42"


@pytest.mark.parametrize("desc", [
    "```\n<!-- PR-AGENT-GENERATED -->\n### **User Description**\nquoted\n```",
    "Text `<!-- pr-agent-generated -->`\n> ### **User Description**\nquoted",
    "<!-- pr-agent-generated -->\n    ### **User Description**\nquoted",
])
def test_marker_anywhere_without_structural_user_header_is_uncached(desc):
    provider = _make_provider(desc)
    reads = []
    provider.get_pr_description_full = lambda: reads.append(True) or desc
    assert provider._is_generated_by_pr_agent(desc.lower()) is True
    assert provider.get_user_description() == ""
    assert provider.get_user_description() == ""
    assert provider.user_description is None
    assert len(reads) == 2


@pytest.mark.parametrize("desc,expected", [
    ("  Plain human text.  ", "Plain human text."),
    ("Fixes #42\n### **User Description**\nHuman\n### **PR Type**\nbug", "Human"),
])
def test_plain_and_extracted_descriptions_use_cached_first_read(desc, expected):
    provider = _make_provider(desc)
    assert provider.get_user_description() == expected

    def unexpected_read():
        pytest.fail("cached description must not read the changed provider body")

    provider.get_pr_description_full = unexpected_read
    assert provider.get_user_description() == expected


def test_full_and_parsed_description_keep_distinct_ownership(monkeypatch):
    from pr_agent import config_loader

    monkeypatch.setattr(config_loader, "get_settings", lambda: types.SimpleNamespace(get=lambda *args: None))
    desc = " \n<!-- pr-agent-generated -->\n### **User Description**\nHuman\n### **PR Type**\nbug\n "
    provider = _make_provider(desc)
    assert provider.get_pr_description(full=True) == desc
    assert provider.get_pr_description(full=False) == "Human"
